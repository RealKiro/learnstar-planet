// ===== 学趣星球 · 宠物特性/技能 =====
// 120 物种 × 5 阶段(卵生→幼年→成长→成熟→传说)的独立「角色特点」与「技能」，
// 保证各类别各宠物各阶段特点互不相同。
// 由 getStagePersonality / getStageAbility 按等级映射取用。

import { getLevelStage } from './petData'

/** 每个物种 5 阶段(egg/baby/growing/mature/legendary)的特性与技能 */
export interface PetTraits {
  /** 5 阶段角色特点 */
  personality: string[]
  /** 5 阶段技能 */
  ability: string[]
}

const STAGE_INDEX: Record<string, number> = { egg: 0, baby: 1, growing: 2, mature: 3, legendary: 4 }

/** 特性构造助手 */
const T = (personality: string[], ability: string[]): PetTraits => ({ personality, ability })

/** 获取某等级的角色特点 */
export function getStagePersonality(speciesId: string, level: number): string {
  const t = PET_TRAITS[speciesId]
  if (!t) return ''
  const idx = STAGE_INDEX[getLevelStage(level)] ?? 0
  return t.personality[idx] || ''
}

/** 获取某等级的技能 */
export function getStageAbility(speciesId: string, level: number): string {
  const t = PET_TRAITS[speciesId]
  if (!t) return ''
  const idx = STAGE_INDEX[getLevelStage(level)] ?? 0
  return t.ability[idx] || ''
}

