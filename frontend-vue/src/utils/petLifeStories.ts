/** 单阶人生档案 */
export interface LifeStageStory {
  /** 本阶人生阶段名（如"朝歌市井"） */
  name: string
  /** 年龄线（如"32岁"） */
  age: string
  /** 关键词（如"朝歌卖面·市井隐志"） */
  keyword: string
  /** 品性性格 */
  character: string
  /** 行为动作 */
  action: string
  /** 服饰梳造 */
  attire: string
  /** 武器功法 */
  technique: string
  /** 进化台词 */
  line: string
  /** 专属诗词 */
  poem: string
  /** SVG 视觉描述（构图/色调/氛围，供绘制） */
  svg: string
  /** 心境 */
  mood: string
}

