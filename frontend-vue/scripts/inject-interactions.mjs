const lines = fs.readFileSync(p, 'utf8').split('\n')
let injected = 0
for (const [id, arr] of Object.entries(DATA)) {
  const start = lines.findIndex(l => l === `  ${id}: {`)
  if (start < 0) { console.error('未找到物种块：' + id); continue }
  // 在该物种块内依序找 6 个 mood 行，在其后插入 interaction
  let stage = 0
  const inserts = []
  for (let i = start + 1; i < lines.length && stage < 6; i++) {
    if (/^  \w+: \{/.test(lines[i])) break // 进入下一个物种块
    if (/mood: '/.test(lines[i])) {
      inserts.push({ at: i, text: arr[stage] || '' })
      stage++
    }
  }
  if (stage < 6) { console.error(`${id} 只定位到 ${stage} 个阶段`); continue }
  for (let k = inserts.length - 1; k >= 0; k--) {
    const { at, text } = inserts[k]
    if (text) { lines.splice(at + 1, 0, `        interaction: '${text}',`); injected++ }
  }
}
fs.writeFileSync(p, lines.join('\n'))
console.log(`已注入 ${injected} 条互动剧情`)
